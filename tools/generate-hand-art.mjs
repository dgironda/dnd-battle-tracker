/**
 * A line that runs along, throws a loop, and carries on.
 *
 * For the path to actually cross itself the loop's horizontal swing has to
 * beat the line's forward travel across the same span — otherwise it is just a
 * bump. So the loop is squeezed into a short span (`span`) and given a wide
 * swing (`ax`). The vertical scale is kept smaller so the loop still fits the
 * 20-unit viewBox.
 */
function loopPath(loops, at, ax, ay, span) {
  const pts = [];
  const total = 260;
  for (let i = 0; i <= total; i++) {
    const t = i / total;
    let x = 4 + t * (W - 8);
    let y = MID + 0.8 * Math.sin(t * 4);
    for (let L = 0; L < loops; L++) {
      const c = at + L * 0.33;
      const d = (t - c) / span;
      if (Math.abs(d) <= 1) {
        const a = (d + 1) * Math.PI;      // one full turn
        x += ax * Math.sin(a);
        y -= ay * (1 - Math.cos(a));
      }
    }
    pts.push([x, y]);
  }
  return "M" + pts.map((p, i) => (i ? "L" : "") + n2(p[0]) + "," + n2(p[1])).join(" ");
}

