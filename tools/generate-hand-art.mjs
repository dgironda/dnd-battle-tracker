/* ------------------------------------------------- the current-turn circle

   A loop scrawled round whoever is up. It is drawn very wide (a table row is
   about 19:1) so the "circle" is really a long racetrack, which is what you get
   when you ring a line of text rather than a word.

   The pen starts before the top of the loop and carries past where it began,
   so the ends cross — the tell that someone drew it in one go without lifting
   off. The radius wanders on three low frequencies so no part of it is a true
   ellipse. */
function circleLoop(seed, cx, cy, rx, ry, from, to, w0, w1, wobble) {
  let r = seed;
  const rnd = () => ((r = (r * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  const a1 = rnd() * 6.283, a2 = rnd() * 6.283, a3 = rnd() * 6.283;
  const STEPS = 190, pts = [];
  for (let i = 0; i <= STEPS; i++) {
    const t = i / STEPS;
    const th = from + (to - from) * t;
    const k = 1 + wobble * (0.5 * Math.sin(th * 2 + a1)
                          + 0.3 * Math.sin(th * 3 + a2)
                          + 0.2 * Math.sin(th * 5 + a3));
    pts.push([
      cx + Math.cos(th) * rx * k,
      cy + Math.sin(th) * ry * k,
      // thin where the pen lands and leaves, heavier through the middle
      w0 + (w1 - w0) * Math.sin(Math.PI * t),
    ]);
  }
  return offsetRibbon(pts);
}

