const n2 = (v) => v.toFixed(2);
const poly = (top, bot) =>
  "M" + n2(top[0][0]) + "," + n2(top[0][1]) + " " +
  top.slice(1).map((p) => "L" + n2(p[0]) + "," + n2(p[1])).join(" ") + " " +
  [...bot].reverse().map((p) => "L" + n2(p[0]) + "," + n2(p[1])).join(" ") + " Z";

/* ------------------------------------------------------------- underlines */

const W = 400, H = 20, SAMPLES = 56, MID = H / 2;

/** Outline a centreline so thickness can vary along the stroke. */
function ribbon(centre, thick) {
  const top = [], bot = [];
  for (let i = 0; i <= SAMPLES; i++) {
    const t = i / SAMPLES, x = 4 + t * (W - 8), y = centre(t), w = thick(t) / 2;
    top.push([x, y - w]);
    bot.push([x, y + w]);
  }
  return poly(top, bot);
}

/** Thin at the ends, swelling through the middle. */
const taper = (a, b) => (t) =>
  a + (b - a) * Math.pow(Math.sin(Math.PI * Math.min(1, t * 1.06)), 0.6);

