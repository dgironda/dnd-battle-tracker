/** Walk a [x, y, width] centreline and give it two sides. */
function offsetRibbon(pts) {
  const top = [], bot = [];
  pts.forEach(([x, y, w], i) => {
    const j = Math.min(i + 1, pts.length - 1), k = Math.max(i - 1, 0);
    const dx = pts[j][0] - pts[k][0], dy = pts[j][1] - pts[k][1];
    const len = Math.hypot(dx, dy) || 1;
    const nx = (-dy / len) * w / 2, ny = (dx / len) * w / 2;
    top.push([x + nx, y + ny]);
    bot.push([x - nx, y - ny]);
  });
  return poly(top, bot);
}

/** One straight tapered stroke. */
function bar(ax, ay, bx, by, w0, w1, sag = 0, steps = 20) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    pts.push([
      ax + (bx - ax) * t,
      ay + (by - ay) * t + Math.sin(Math.PI * t) * sag,
      w0 + (w1 - w0) * t,
    ]);
  }
  return offsetRibbon(pts);
}

/** Two segments, so the stroke can dig in at the turn and flick out thin. */
function tick(ax, ay, bx, by, cx, cy, w0, w1, w2, w3) {
  const STEPS = 26, pts = [];
  const seg = (p, q, wa, wb, skipFirst) => {
    for (let i = skipFirst ? 1 : 0; i <= STEPS; i++) {
      const t = i / STEPS;
      pts.push([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t, wa + (wb - wa) * t]);
    }
  };
  seg([ax, ay], [bx, by], w0, w1, false);
  seg([bx, by], [cx, cy], w2, w3, true);
  return offsetRibbon(pts);
}

/**
 * A box scribbled out. Back-and-forth passes that overshoot the sides by
 * different amounts each time, because nobody fills a box in neatly — the
 * turns at the ends are where it spills over.
 */
function scribble(seed, passes, x0, x1, y0, y1, w, over) {
  let r = seed;
  const rnd = () => ((r = (r * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  const pts = [];
  for (let p = 0; p < passes; p++) {
    const t = passes === 1 ? 0.5 : p / (passes - 1);
    const y = y0 + (y1 - y0) * t;
    const ltr = p % 2 === 0;
    const a = (ltr ? x0 : x1) + (ltr ? -1 : 1) * rnd() * over;
    const b = (ltr ? x1 : x0) + (ltr ? 1 : -1) * rnd() * over;
    const STEPS = 9;
    for (let i = p === 0 ? 0 : 1; i <= STEPS; i++) {
      const s = i / STEPS;
      pts.push([
        a + (b - a) * s,
        y + Math.sin(s * Math.PI) * (p % 2 ? 1.8 : -1.8) + (rnd() - 0.5) * 1.6,
        w * (0.85 + rnd() * 0.3),
      ]);
    }
  }
  return offsetRibbon(pts);
}

