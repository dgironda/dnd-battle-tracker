/**
 * Regenerates the hand-drawn SVGs the battle tracker uses:
 *
 *   underline_pencil-1..5.svg   the pencil underline under a combatant's name
 *   checkbox_hand-1..5.svg      the action / bonus / move / reaction checkbox
 *   check_hand-1..3.svg         the tick that goes in it
 *
 * These are generated rather than drawn because each outline is sampled around
 * a centreline — that is what lets a stroke take a real shape (a sag, a
 * swoosh, a wave) and swell and taper the way pressure does. The consequence
 * is that the `d` attributes are long polylines and are NOT hand-editable:
 * change the maths here and re-run.
 *
 *     node tools/generate-hand-art.mjs
 */
