#!/usr/bin/env node
/**
 * Writes docs/MAP.md: one line per source file, its path and the first
 * sentence of its header comment, grouped by folder. A new session reads the
 * map for the folder it needs instead of opening every file to find its way.
 *
 * Run `npm run map` after adding, moving or re-describing files. `--check`
 * exits 1 when docs/MAP.md is out of date (for a pre-commit hook or CI).
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROOTS = ['src', 'functions', 'workers', 'server', 'view'].filter((d) => existsSync(join(root, d)));
const CODE = /\.(tsx?|mjs|cjs|js)$/;
const SKIP = /(^|\/)(node_modules|dist|\.wrangler)(\/|$)|\.d\.ts$/;
const MAX = 160;

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    const rel = relative(root, full).split(sep).join('/');
    if (SKIP.test(rel)) continue;
    if (entry.isDirectory()) out.push(...walk(full));
    else if (CODE.test(entry.name)) out.push(rel);
  }
  return out;
}

const IMPORT_START = /^import\b/;
const IMPORT_DONE = /\bfrom\s+['"]|^import\s+['"]|;$/;
const PREAMBLE = /^$|^('use |"use |#!)|^export \* from\b/;
const isComment = (l) => l.startsWith('/*') || l.startsWith('//');

/** Where the header comment starts: past imports and directives, or -1 when code comes first. */
function headerStart(lines) {
  let inImport = false;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (inImport) inImport = !IMPORT_DONE.test(l);
    else if (isComment(l)) return i;
    else if (IMPORT_START.test(l)) inImport = !IMPORT_DONE.test(l);
    else if (!PREAMBLE.test(l)) return -1;
  }
  return -1;
}

/** The comment's lines from `i`: a block to its close, or a run of `//` lines. */
function commentLines(lines, i) {
  if (lines[i].startsWith('//')) {
    const run = [];
    for (let j = i; j < lines.length && lines[j].startsWith('//'); j++) run.push(lines[j].replace(/^\/\/+/, ''));
    return run;
  }
  const close = lines.findIndex((l, j) => j >= i && l.endsWith('*/'));
  return lines.slice(i, close === -1 ? lines.length : close + 1).map((l) => l.replace(/^\/\*+|\*+\/$|^\*+/g, ''));
}

/** The comment's first sentence, cut to MAX. */
function firstSentence(words) {
  const joined = words.map((w) => w.trim()).filter((w) => w && !/^(eslint|@ts-|prettier|biome)/.test(w)).join(' ').replace(/\s+/g, ' ');
  const sentence = (joined.match(/^.*?[.!?](?=\s|$)/) ?? [joined])[0];
  return sentence.length > MAX ? `${sentence.slice(0, MAX - 1).trimEnd()}…` : sentence;
}

/** The first comment in the file's opening lines, as one line; '' for none. */
function headerOf(text) {
  const lines = text.split(/\r?\n/).slice(0, 80).map((l) => l.trim());
  const at = headerStart(lines);
  return at === -1 ? '' : firstSentence(commentLines(lines, at));
}

const files = ROOTS.flatMap((d) => walk(join(root, d))).sort();
const byFolder = new Map();
for (const f of files) {
  const folder = f.includes('/') ? f.slice(0, f.lastIndexOf('/')) : '.';
  if (!byFolder.has(folder)) byFolder.set(folder, []);
  byFolder.get(folder).push(f);
}

let md = '# Source map\n\nGenerated by `npm run map` from each file\'s header comment. Don\'t edit by hand; fix the comment and rerun.\nFiles without a header comment show "(no header)": adding one is welcome.\n';
for (const [folder, list] of byFolder) {
  md += `\n## ${folder}/\n\n`;
  for (const f of list) md += `- \`${f.slice(folder.length + 1)}\`: ${headerOf(readFileSync(join(root, f), 'utf8')) || '(no header)'}\n`;
}

const target = join(root, 'docs', 'MAP.md');
if (process.argv.includes('--check')) {
  const now = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (now !== md) {
    console.error('docs/MAP.md is out of date: run `npm run map`.');
    process.exit(1);
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, md);
  console.log(`docs/MAP.md: ${files.length} files in ${byFolder.size} folders.`);
}
